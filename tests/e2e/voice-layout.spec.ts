import { expect, test } from '@playwright/test';
import { changeLanguage, audioSettings, workspaceLink } from './workspace-navigation';
import { expectReadableText } from './readability';

test('dedicated voice room preserves one muted session across navigation and exposes deliberate local video controls', async ({ page, context }, info) => {
  await context.grantPermissions(['microphone', 'camera']);
  await page.goto('/register');
  await page.getByLabel('Display name', { exact: true }).fill('Voice layout owner');
  await page.getByLabel('Email address', { exact: true }).fill(`voice-layout-${crypto.randomUUID()}@example.test`);
  await page.getByLabel('Password', { exact: true }).fill('Synthetic voice layout 42');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome, Voice layout owner.' })).toBeVisible();
  await workspaceLink(page, 'Communities');
  await page.getByLabel('Community name', { exact: true }).fill('Night Crew');
  await page.getByRole('button', { name: 'Create community', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Night Crew', exact: true })).toBeVisible();
  let joins = 0;
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/voice/join')) joins++; });
  await workspaceLink(page, 'Voice room');
  await expect(page).toHaveURL(/\/communities\/[^/]+\/voice$/);
  const room = page.getByRole('region', { name: 'Voice room', exact: true });
  await expect(room.getByText('No one is in voice yet.', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Manage access', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Join voice', exact: true }).click();
  const dock = page.getByRole('region', { name: 'Voice controls', exact: true });
  await expect(dock).toContainText('Connected · Muted', { timeout: 20_000 });
  const self = room.locator('.voice-participants li').filter({ hasText: 'Voice layout owner' });
  await expect(self).toContainText(' · You');
  await expect(self).toContainText('Microphone muted');
  await expect(self).not.toContainText('Listen only');
  await expectReadableText(room);
  await page.screenshot({ path: info.outputPath('voice-room-muted.png'), fullPage: true });
  await page.getByRole('button', { name: 'Enable camera', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Stop camera', exact: true })).toBeEnabled();
  await expect(page.locator('.voice-videos video')).toHaveCount(0);
  const view = page.getByRole('button', { name: 'View shared video (1)', exact: true });
  await view.click();
  const video = page.locator('.voice-videos video');
  await expect(video).toHaveCount(1);
  await video.scrollIntoViewIfNeeded();
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).videoWidth)).toBeGreaterThan(0);
  const focus = page.getByRole('button', { name: 'Focus video', exact: true });
  const galleryHeight = (await page.getByRole('region', { name: 'Shared video', exact: true }).boundingBox())!.height;
  await focus.click();
  await expect(page.locator('main')).not.toBeVisible();
  expect((await page.getByRole('region', { name: 'Shared video', exact: true }).boundingBox())!.height).toBeGreaterThan(galleryHeight);
  await page.screenshot({ path: info.outputPath('local-camera-focus.png'), fullPage: true });
  await page.getByRole('button', { name: 'Show all videos', exact: true }).press('Escape');
  await expect(page.locator('main')).toBeVisible(); await expect(focus).toBeFocused();
  await focus.click();
  await workspaceLink(page, 'general');
  await expect(page.getByRole('heading', { name: '#general', exact: true })).toBeVisible();
  await expect(video).toHaveCount(1); expect(joins).toBe(1);
  const hide = page.getByRole('button', { name: 'Hide shared video', exact: true });
  await hide.click(); await expect(video).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Stop camera', exact: true })).toBeEnabled();
  await view.click();
  await page.getByRole('button', { name: 'Stop your camera', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Shared video', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Enable camera', exact: true })).toBeEnabled();
  await workspaceLink(page, 'Voice room');
  await page.getByRole('button', { name: 'Deafen', exact: true }).click();
  await expect(room).toContainText('Deafened');
  await page.getByRole('button', { name: 'Undeafen', exact: true }).click();
  await changeLanguage(page, 'ru');
  await expect(page.getByRole('heading', { name: 'Голосовой канал', exact: true, level: 1 })).toBeVisible();
  const translatedParticipants = page.getByRole('region', { name: 'Голосовой канал', exact: true }).locator('.voice-participants');
  await expect(translatedParticipants).toContainText(' · Вы');
  await expect(translatedParticipants).toContainText('Микрофон выключен');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('voice-room-ru.png'), fullPage: true });
  // Return to the translated dock without starting another join.
  await changeLanguage(page, 'en');
  await audioSettings(page);
  await expect(page.getByRole('checkbox', { name: 'Noise suppression', exact: true })).toBeVisible();
  await page.keyboard.press('Escape'); expect(joins).toBe(1);
  await page.getByRole('button', { name: 'Leave voice', exact: true }).click();
  await expect(dock).toHaveCount(0);
});

test('leaving from your participant row closes your session without moderator attribution and allows rejoining', async ({ page }, info) => {
  await page.goto('/register');
  await page.getByLabel('Display name', { exact: true }).fill('Self leave owner');
  await page.getByLabel('Email address', { exact: true }).fill(`self-leave-${crypto.randomUUID()}@example.test`);
  await page.getByLabel('Password', { exact: true }).fill('Synthetic self leave 42');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome, Self leave owner.' })).toBeVisible();
  await workspaceLink(page, 'Communities');
  await page.getByLabel('Community name', { exact: true }).fill('Self leave room');
  await page.getByRole('button', { name: 'Create community', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Self leave room', exact: true })).toBeVisible();
  await workspaceLink(page, 'Voice room');
  let moderated = 0;
  let leaves = 0;
  page.on('request', request => {
    if (request.method() !== 'POST') return;
    if (request.url().endsWith('/voice/disconnect')) moderated++;
    if (request.url().endsWith('/voice/leave')) leaves++;
  });
  await page.getByRole('button', { name: 'Join voice', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Voice controls' })).toContainText('Connected');
  await changeLanguage(page, 'ru');
  const row = page.locator('.voice-participants li').filter({ hasText: 'Self leave owner' });
  await row.getByRole('button', { name: 'Выйти из канала', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Управление голосом' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Войти в голосовой канал', exact: true })).toBeEnabled();
  await expect(row).toHaveCount(0);
  await expect(page.getByRole('alert')).toHaveCount(0);
  expect(leaves).toBe(1);
  expect(moderated).toBe(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('self-left-ru.png'), fullPage: true });
  // A temporary control-service failure must remain actionable after a voluntary leave.
  await page.route('**/voice/join', route => route.fulfill({ status: 503, contentType: 'application/problem+json', body: JSON.stringify({ title: 'Voice service is unavailable. Try again shortly.' }) }), { times: 1 });
  await page.getByRole('button', { name: 'Войти в голосовой канал', exact: true }).click();
  const dock = page.getByRole('region', { name: 'Управление голосом' });
  await expect(dock.getByRole('alert')).toContainText('Голосовой сервис недоступен');
  await dock.getByRole('button', { name: 'Переподключиться к голосовому каналу', exact: true }).click();
  await expect(dock).toContainText('Подключено · Микрофон выключен', { timeout: 20_000 });
  expect(moderated).toBe(0);
  await expectReadableText(page.getByRole('region', { name: 'Голосовой канал', exact: true }));
  await page.screenshot({ path: info.outputPath('self-rejoined-ru.png'), fullPage: true });
  await dock.getByRole('button', { name: 'Выйти из голосового канала', exact: true }).click();
  await expect(dock).toHaveCount(0);
});
