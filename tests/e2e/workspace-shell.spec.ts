import { expect, test } from '@playwright/test';
import { audioSettings, joinVoice, workspaceLink } from './workspace-navigation';

test('workspace navigation preserves a muted voice session, settings and keyboard focus across routes', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/register');
  await page.getByLabel('Display name', { exact: true }).fill('Workspace owner');
  await page.getByLabel('Email address', { exact: true }).fill(`workspace-${crypto.randomUUID()}@example.test`);
  await page.getByLabel('Password', { exact: true }).fill('Synthetic workspace browser 42');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome, Workspace owner.' })).toBeVisible();
  await workspaceLink(page, 'Communities');
  const name = 'Evening crew — a community with a long name';
  await page.getByLabel('Community name', { exact: true }).fill(name);
  await page.getByRole('button', { name: 'Create community', exact: true }).click();
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  await workspaceLink(page, 'general');
  await expect(page.getByRole('heading', { name: '#general', exact: true })).toBeVisible();
  await page.getByLabel('Message', { exact: true }).fill('The workspace keeps our conversation and voice together.');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(page.getByRole('list', { name: 'Messages', exact: true })).toContainText('The workspace keeps our conversation');
  let joins = 0;
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/voice/join')) joins++; });
  await joinVoice(page);
  const dock = page.getByRole('region', { name: 'Voice controls', exact: true });
  await expect(dock).toContainText('Connected · Muted', { timeout: 15_000 });
  await workspaceLink(page, 'general');
  await expect(dock.getByRole('button', { name: 'Enable microphone', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await expect(page.getByRole('slider', { name: 'Output volume', exact: true })).not.toBeVisible();
  await page.screenshot({ path: info.outputPath('workspace-channel.png'), fullPage: true });
  await audioSettings(page);
  const slider = page.getByRole('slider', { name: 'Output volume', exact: true });
  await slider.focus(); await page.keyboard.press('Home');
  await expect(slider).toHaveValue('0');
  await expect(page.getByRole('checkbox', { name: 'Noise suppression', exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath('workspace-audio.png'), fullPage: true });
  await page.keyboard.press('Escape');
  await expect(dock.getByRole('button', { name: 'Audio and sharing settings', exact: true })).toBeFocused();
  await workspaceLink(page, 'Messages');
  await expect(page.getByRole('heading', { name: 'Direct messages', exact: true })).toBeVisible();
  await expect(dock).toContainText('Connected · Muted');
  await audioSettings(page); await expect(slider).toHaveValue('0');
  await page.getByRole('button', { name: 'Close settings', exact: true }).click();
  const menu = page.getByRole('button', { name: 'Open navigation', exact: true });
  if (await menu.isVisible()) {
    await menu.click();
    const navigation = page.getByRole('dialog', { name: 'Workspace navigation', exact: true });
    await expect(navigation).toBeVisible();
    await page.screenshot({ path: info.outputPath('workspace-navigation.png'), fullPage: true });
    await page.keyboard.press('Escape');
    await expect(menu).toBeFocused();
  }
  await workspaceLink(page, `Open ${name}`);
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  await workspaceLink(page, 'Gatherings');
  await expect(page.getByRole('heading', { name: 'Gatherings', exact: true })).toBeVisible();
  await expect(dock).toContainText('Connected · Muted');
  expect(joins).toBe(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await dock.getByRole('button', { name: 'Leave voice', exact: true }).click();
  await expect(dock).toHaveCount(0);
  expect(errors).toEqual([]);
});
