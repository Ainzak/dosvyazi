import { expect, test } from '@playwright/test';
import { composerTools, workspaceLink } from './workspace-navigation';
import { expectReadableText } from './readability';

test('conversation keeps composer visible, supports keyboard send and exposes actions without losing drafts', async ({ page }, info) => {
  await page.goto('/register');
  await page.getByLabel('Display name', { exact: true }).fill('Conversation owner');
  await page.getByLabel('Email address', { exact: true }).fill(`conversation-ui-${crypto.randomUUID()}@example.test`);
  await page.getByLabel('Password', { exact: true }).fill('Synthetic conversation layout 42');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome, Conversation owner.' })).toBeVisible();
  await workspaceLink(page, 'Communities');
  await page.getByLabel('Community name', { exact: true }).fill('Night Crew');
  await page.getByRole('button', { name: 'Create community', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Night Crew', exact: true })).toBeVisible();
  await workspaceLink(page, 'general');
  const composer = page.getByLabel('Message', { exact: true });
  const submissions: string[] = [];
  page.on('request', request => { if (request.method() === 'POST' && /\/(messages|attachments)$/.test(request.url())) submissions.push(request.url()); });
  await composer.fill('   '); await composer.press('Enter');
  expect(submissions).toHaveLength(0);
  await expect(composer).toHaveValue('   ');
  await composer.fill('One more round?'); await composer.press('Enter');
  const messages = page.getByRole('list', { name: 'Messages', exact: true });
  await expect(messages).toContainText('One more round?');
  await composer.fill('First line'); await composer.press('Shift+Enter'); await composer.pressSequentially('Second line');
  await expect(composer).toHaveValue('First line\nSecond line'); await composer.press('Enter');
  await expect(messages).toContainText('First line\nSecond line');
  await composer.fill('Keep this draft');
  await page.getByRole('button', { name: 'Search this channel', exact: true }).click();
  await page.getByLabel('Search this channel', { exact: true }).fill('round');
  await page.getByLabel('Search this channel', { exact: true }).press('Escape');
  await expect(composer).toHaveValue('Keep this draft');
  const row = messages.locator(':scope > li').filter({ hasText: 'One more round?' });
  const actions = row.locator('summary'); await actions.click();
  await expect(row.getByRole('button', { name: 'Edit message by Conversation owner', exact: true })).toBeVisible();
  await actions.press('Escape'); await expect(actions).toBeFocused();
  await expect(row.getByRole('button', { name: 'Edit message by Conversation owner', exact: true })).not.toBeVisible();
  await composerTools(page);
  await page.getByLabel('Attach a file', { exact: true }).setInputFiles({ name: 'unsafe.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') });
  const sentBeforeInvalidFile = submissions.length;
  await composer.press('Enter');
  expect(submissions).toHaveLength(sentBeforeInvalidFile);
  await expect(composer).toHaveValue('Keep this draft');
  await expect(page.getByRole('alert')).toContainText('Choose a nonempty');
  await composerTools(page);
  await page.getByLabel('Attach a file', { exact: true }).setInputFiles({ name: 'tonight.txt', mimeType: 'text/plain', buffer: Buffer.from('One more round') });
  await page.getByRole('button', { name: 'Close attachments', exact: true }).click();
  await expect(page.getByText('Selected file: tonight.txt', { exact: true })).toBeVisible();
  await expect(composer).toHaveValue('Keep this draft');
  const bounds = await composer.boundingBox(); expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(page.viewportSize()!.height);
  await expectReadableText(row);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('conversation-layout.png'), fullPage: true });
  await composerTools(page);
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  const sentFile = messages.locator(':scope > li').filter({ hasText: 'Keep this draft' });
  await expect(sentFile.getByRole('button', { name: 'Download file: tonight.txt', exact: true })).toBeVisible();
  await expect(page.getByRole('region', { name: 'Attachments and recording', exact: true })).not.toBeVisible();
  await sentFile.locator('summary').click();
  await expect(sentFile.getByRole('button', { name: 'Edit message by Conversation owner', exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath('conversation-after-send.png'), fullPage: true });
});
