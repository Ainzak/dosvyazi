export function translate(locale: Locale, text: string, values: Record<string, string | number> = {}) {
  const core = text.trim();
  const message = locale === 'ru' ? russian[core] ?? core : core;
  const formatted = message.replace(/\{(\w+)\}/g, (placeholder, key: string) => Object.hasOwn(values, key) ? String(values[key]) : placeholder);
  return text.slice(0, text.length - text.trimStart().length) + formatted + text.slice(text.trimEnd().length);
}
